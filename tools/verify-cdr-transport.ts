/**
 * Does the published CDR SDK actually work against our proxy?
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS IS A SEPARATE TOOL AND NOT A UNIT TEST
 *
 * `tests/cdr-transport.test.ts` proves the SDK builds the right URLs. It cannot prove the
 * keeper accepts them, because it stubs `fetch`. The gap between those two things is exactly
 * where the previous attempt at this claim went wrong: `/dkg/cdr_partials` was probed with a
 * hand-written query string, the keeper returned HTTP 500
 * (`requester_pub_key_hex must decode to an uncompressed secp256k1 public key`), and that was
 * reported as evidence the endpoint worked. It was not. It was evidence the endpoint *validates
 * its input* — the request was malformed and the keeper said so.
 *
 * So this tool drives the **real SDK functions** against the **real deployed proxy** with a
 * **real secp256k1 public key**, generated by the same `generateEphemeralKeyPair()` the SDK
 * calls internally when it performs a genuine read (`consumer.js`). A success here means the
 * SDK's own request shape survives the proxy's allowlist and satisfies the keeper.
 *
 * WHAT THIS TOOL IS NOT. It cannot show partials, because a key that has never read has none.
 * Real partial retrieval through this same proxy is proven by `npm run verify:read`, which
 * performs an actual licensed read and watches the endpoint go from "none yet" to a full
 * threshold set. Read section 4 below before drawing a conclusion from the partials check here.
 *
 * Run:  npm run verify:transport
 *       npm run verify:transport -- http://localhost:4180/api/cdr
 * ─────────────────────────────────────────────────────────────────────────────
 */

import {
  generateEphemeralKeyPair,
  queryAllRegistrations,
  queryCDRPartials,
  queryDKGNetwork,
  queryGlobalPubKey,
  queryLatestActiveDKGNetwork,
} from "@piplabs/cdr-sdk";

import { CANONICAL_VAULT } from "../lib/protocol/canonical-vault";

const DEFAULT_BASE = "https://licensevault.vercel.app/api/cdr";

const base = (process.argv[2] ?? DEFAULT_BASE).replace(/\/+$/, "");

interface Check {
  name: string;
  ok: boolean;
  detail: string;
}

const checks: Check[] = [];

function record(name: string, ok: boolean, detail: string): void {
  checks.push({ name, ok, detail });
  const mark = ok ? "PASS" : "FAIL";
  console.log(`  [${mark}] ${name}\n         ${detail}`);
}

async function main(): Promise<void> {
  console.log(`\nCDR transport verification against ${base}\n`);
  console.log(`  vault uuid ${CANONICAL_VAULT.uuid}  ·  chain ${CANONICAL_VAULT.chainId}\n`);

  // ── 1. The group public key ────────────────────────────────────────────────
  try {
    const key = await queryGlobalPubKey({ apiUrl: base });
    record(
      "queryGlobalPubKey",
      key.length === 32,
      `${key.length} bytes · ${Buffer.from(key).toString("hex").slice(0, 32)}…`,
    );
  } catch (error) {
    record("queryGlobalPubKey", false, String(error));
  }

  // ── 2. The active DKG network ──────────────────────────────────────────────
  let round: number | undefined;
  try {
    const network = await queryLatestActiveDKGNetwork({ apiUrl: base });
    round = network.round;
    record(
      "queryLatestActiveDKGNetwork",
      network.activeValSet.length > 0,
      `round ${network.round} · ${network.activeValSet.length} validators · threshold quorum is what the read must reach`,
    );
  } catch (error) {
    record("queryLatestActiveDKGNetwork", false, String(error));
  }

  // ── 3. A round-scoped endpoint, using the round we just learned ────────────
  if (round !== undefined) {
    try {
      const same = await queryDKGNetwork({ apiUrl: base, round });
      record(
        "queryDKGNetwork(round)",
        same.round === round,
        `asked for round ${round}, got round ${same.round}`,
      );
    } catch (error) {
      record("queryDKGNetwork(round)", false, String(error));
    }

    try {
      const regs = await queryAllRegistrations({ apiUrl: base, round });
      record(
        "queryAllRegistrations(round)",
        Array.isArray(regs),
        `${regs.length} registration(s) for round ${round}`,
      );
    } catch (error) {
      record("queryAllRegistrations(round)", false, String(error));
    }
  }

  // ── 4. A real SDK-generated partials request, from a key that has never read ─
  //
  // The key is generated by the SDK's own helper, so the request is byte-for-byte the shape a
  // real read produces. What it CANNOT show is partials, because a fresh key has none — the
  // keeper answers `partial decryption submission not found` as HTTP 500.
  //
  // ─────────────────────────────────────────────────────────────────────────────
  // MEASURED 2026-10-13, and the reason this check is worded so carefully.
  //
  // There are TWO different HTTP 500s on this endpoint and they mean opposite things:
  //
  //   1. `requester_pub_key_hex must decode to an uncompressed secp256k1 public key`
  //      — the request was malformed. This is the one an earlier session probed by hand and
  //        wrongly reported as proof the endpoint worked. It is not proof of anything except
  //        that the keeper validates its input.
  //
  //   2. `partial decryption submission not found`
  //      — the request was well-formed, understood, and answered: no validator has produced a
  //        partial for this requester key. Correct semantics, unhelpful status code.
  //
  // The SDK tolerates (2): `consumer.js` `collectPartials` wraps its `queryCDRPartials` call in
  // try/catch and treats any throw as "transient REST error — retry on next poll tick", so a
  // real read's polling loop is not broken by it. That is why this check can pass on a 500 —
  // but passing here is a statement about the TRANSPORT, not about partial retrieval.
  //
  // Partial retrieval itself was proven separately, by `npm run verify:read`: a real read from
  // the license-holding wallet was observed through this same deployed proxy going from that
  // 500 to **5 real submissions in round 46**, then decrypting the committed ciphertext to the
  // recorded plaintext hash. Do not read this check as a substitute for that one.
  // ─────────────────────────────────────────────────────────────────────────────
  const keypair = generateEphemeralKeyPair();
  const requesterPubKeyHex = `0x${Buffer.from(keypair.publicKey).toString("hex")}`;

  try {
    const rounds = await queryCDRPartials({
      apiUrl: base,
      uuid: CANONICAL_VAULT.uuid,
      requesterPubKeyHex,
    });

    record(
      "queryCDRPartials (real SDK request shape, real 65-byte secp256k1 key)",
      Array.isArray(rounds),
      `the keeper answered with ${rounds.length} round(s) of partials — the documented empty ` +
        `answer for a key that has never read. What this proves is the REQUEST: a real ` +
        `SDK-generated partials query survives the allowlist and satisfies the keeper.`,
    );
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);

    // Our own route's wordings. Any of these means the request never reached a semantic answer
    // and the proxy — not the keeper — is the problem.
    const routeFailed =
      /not one of them|Nothing was forwarded|did not answer|Too many keeper requests/.test(message);

    const noPartialsYet = message.includes("partial decryption submission not found");

    record(
      "queryCDRPartials (real SDK request shape, real 65-byte secp256k1 key)",
      !routeFailed,
      routeFailed
        ? `OUR PROXY REFUSED OR COULD NOT REACH THE KEEPER: ${message}`
        : noPartialsYet
          ? `the keeper answered about THIS requester key — "no partials exist for it yet" — ` +
            `returned as HTTP 500 rather than the documented empty list. Well-formed input, ` +
            `understood request, honest answer with an unhelpful status. This is NOT evidence ` +
            `that partial retrieval works; that needs a real read and is proven by ` +
            `\`npm run verify:read\`.`
          : `the keeper gave an answer this tool does not recognise, which is worth reading: ${message}`,
    );
  } finally {
    // The SDK's contract: the caller zeroes the private key. This tool never uses it, but the
    // rule is the rule, and a tool that ignores it is the wrong example to leave in the repo.
    keypair.privateKey.fill(0);
  }

  // ── 5. The proxy still refuses what it should ─────────────────────────────
  try {
    const response = await fetch(`${base}/shutdown`);
    record(
      "an unlisted path is refused by the proxy",
      response.status === 404,
      `HTTP ${response.status} for /shutdown`,
    );
  } catch (error) {
    record("unlisted path refused", false, String(error));
  }

  const failed = checks.filter((check) => !check.ok);
  console.log(
    `\n  ${checks.length - failed.length} passed · ${failed.length} failed` +
      `\n  NOTE: this proves the transport — that the SDK's own requests survive the proxy and` +
      `\n  satisfy the keeper. It does NOT prove a protected read or partial retrieval.` +
      `\n  Those need a funded licence-holding wallet: \`npm run verify:read\`.\n`,
  );

  if (failed.length > 0) process.exitCode = 1;
}

// `tsx` compiles this to CommonJS, where top-level `await` is a transform error. Fire and forget,
// but keep the rejection visible — a tool that fails silently is the failure mode this repo has
// been bitten by five times.
main().catch((error: unknown) => {
  console.error("transport verification crashed:", error);
  process.exitCode = 1;
});
